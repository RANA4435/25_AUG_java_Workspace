package com.kodewala.constructor8;

public class Details {
	String name;
	String item;
	int quantity;
	int price;
	String payment;
	public Details(String name, String item, int quantity, int price, String payment) {

		this.name = name;
		this.item = item;
		this.quantity = quantity;
		this.price = price;
		this.payment = payment;
	}
	
	

}
