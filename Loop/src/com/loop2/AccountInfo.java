package com.loop2;

public class AccountInfo {
	String name;
	String accNo;
	int balance;
	String sender;
	String reciever;
	int amount;
	public AccountInfo(String name, String accNo, int balance, String sender, String reciever, int amount) {
		super();
		this.name = name;
		this.accNo = accNo;
		this.balance = balance;
		this.sender = sender;
		this.reciever = reciever;
		this.amount = amount;
	}
	
	

}
