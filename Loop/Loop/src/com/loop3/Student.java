package com.loop3;

public class Student {
	String name;
	String behavior;
	int age ;
	int marks;
	int standard;
	String subject;
	String course;
	public Student(String name, String behavior, int age, int marks, int standard, String subject, String course) {
		super();
		this.name = name;
		this.behavior = behavior;
		this.age = age;
		this.marks = marks;
		this.standard = standard;
		this.subject = subject;
		this.course = course;
	}
	
	
	

}
