package com.loop1;
public class Student {

    String name;
    int age;
    int marks;
    int fees;
    String subject;
    String section;

    public Student(String name, int age, int marks, int fees,
                   String subject, String section) {

        super();

        this.name = name;
        this.age = age;
        this.marks = marks;
        this.fees = fees;
        this.subject = subject;
        this.section = section;
    }
}